"""Robot geometry from the digital twin (single source of truth) + reality->model calibration hook.

  src/twin_geometry.json   generated by scripts/gen_twin_geometry.py from the twin URDF (per KEVIN_TIRE profile)
  src/calibration.json     optional measured corrections (reality -> model), identity when absent:
      {"wheel_r_scale": 1.0, "track_scale": 1.0,
       "frames": {"rs1_depth": {"dxyz": [0,0,0], "drpy_deg": [0,0,0]}, ...},
       "imu": {"gyro_bias": [0,0,0], "gyro_scale": 1.0}}
Every consumer (robot_config, vision, cuvslam_tracker, nav, emulator) reads these values; nothing is duplicated."""
import json, math, os
