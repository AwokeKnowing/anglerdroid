def _rpy(r, p, y):
    cr, sr, cp, sp, cy, sy = math.cos(r), math.sin(r), math.cos(p), math.sin(p), math.cos(y), math.sin(y)
    return np.array([[cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr], [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr], [-sp, cp * sr, cp * cr]])


def frame(name):
    """(xyz (3,), R (3,3) optical->base) for a twin frame, with calibration applied."""
    f = _G["frames"][name]; t = np.array(f["xyz"], float); R = np.array(f["R"], float)
    c = CALIB.get("frames", {}).get(name)
    if c:
        t = t + np.array(c.get("dxyz", [0, 0, 0]), float); R = _rpy(*[math.radians(v) for v in c.get("drpy_deg", [0, 0, 0])]) @ R
    return t, R


